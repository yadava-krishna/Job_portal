def _norm(value):
    if not value:
        return ""
    value = value.lower().replace("&", " and ")
    return " ".join(re.sub(r"[^a-z0-9]+", " ", value).split())


def _dedup_key(company, title):
    c = " ".join(_NOISE_COMPANY.sub(" ", _norm(company)).split())
    t = _norm(title)
    t = re.sub(r"\b(sr|senior)\b", "senior", t)
    t = re.sub(r"\b(jr|junior)\b", "junior", t)
    t = " ".join(_NOISE_TITLE.sub(" ", t).split())
    return f"{c}|{t}"[:400] if c and t else None


def _canonical_url(url):
    if not url:
        return None
    try:
        parts = urlsplit(url.strip())
    except ValueError:
        return None
    if not parts.netloc:
        return None
    host = parts.netloc.lower().removeprefix("www.")
    query = urlencode(sorted((k, v) for k, v in parse_qsl(parts.query) if k.lower() in _KEEP_QUERY))
    path = re.sub(r"/+", "/", parts.path).rstrip("/")
    return urlunsplit(("", host, path, query, "")).lstrip("/")[:1000]


